export function accountKindOf(name) {
  const s = name || '';
  if (s.includes('微信') || s.includes('零钱')) return 'wechat';
  if (s.includes('支付宝') || s.includes('余额宝') || s.includes('花呗')) return 'alipay';
  if (s.includes('京东') || s.includes('白条') || s.includes('小金库')) return 'jd';
  if (s.includes('银行') || s.includes('信用卡') || s.includes('银联') || s.includes('云闪付')) return 'bank';
  if (s.includes('现金')) return 'cash';
  return 'other';
}

// 把账单里的账户名收敛成统一账户名：
// 1) 去掉「&红包」「&奖励金抵扣」这类优惠组合后缀
// 2) 去掉「微信-」这类渠道前缀
// 3) 银行全称/旧名统一成新名
// 4) 命中归并表就返回统一账户
export function normalizeAccountName(name) {
  let s = String(name || '').trim();
  if (!s || s === '/') return '';
  s = s.split('&')[0].trim();
  s = s.replace(/\s+/g, ' ');
  for (const [pattern, replacement] of ACCOUNT_PREFIX_RULES) {
    if (pattern.test(s)) {
      s = replacement ? (replacement + s.replace(pattern, '')) : s.replace(pattern, '');
      break;
    }
  }
  if (/^账户余额/.test(s) || /^余额(?!宝)/.test(s)) s = '支付宝余额';
  s = ACCOUNT_RENAME[s] || s.replace(/^中国(?!人民)/, ''); // 中国工商银行 -> 工商银行
  if (ACCOUNT_MERGE[s]) return ACCOUNT_MERGE[s];
  return s;
}

// 账户归并名 -> 该组的其它历史名称（用于建别名，兼容旧账单）
export function accountAliasSources() {
  const map = new Map();
  for (const [alias, target] of Object.entries(ACCOUNT_MERGE)) {
    if (alias === target) continue;
    if (!map.has(target)) map.set(target, []);
    map.get(target).push(alias);
  }
  return map;
}

// 外部分类名 -> [一级, 二级]。带空格的复合分类取第一段。
export function resolveCategoryPath(name, kind) {
  const raw = String(name || '').trim();
  if (!raw) return null;
  const table = EXTERNAL_CATEGORY[kind];
  if (!table) return null;
  if (table[raw]) return table[raw];
  const first = raw.split(/[\s/、,]+/)[0];
  if (table[first]) return table[first];
  return null;
}

export function categoryTreeEntries(kind) {
  return CATEGORY_TREE[kind] || [];
}
